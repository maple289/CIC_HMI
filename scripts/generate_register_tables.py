"""Render the complete per-family inventory from reviewed profile metadata."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from prevex_hmi.profiles import PROFILES
from prevex_hmi.profiles.lel700 import PROFILE as LEL700


def render() -> str:
    lines = ["# Complete register inventories", "", "Generated by scripts/generate_register_tables.py. See REGISTER_SPECIFICATION.md for conversion formulas and shared protocol rules. RW is manufacturer access, not permission to write hardware. Every row requires Administrator for candidate configuration; commands require a separate authorized workflow. Unknown bounds block writes.", ""]
    for family, profile in {**PROFILES,"LEL 700-series (H7FTA700 Rev D)":LEL700}.items():
        lines += [f"## {family}", "", "| Number | Name / meaning | Format | Signed | Units | Precision | Access / simulation policy | Range or choices | Source | Restrictions |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for r in profile.registers.values():
            bounds = str(r.choices) if r.choices else f"{r.minimum or '?'}..{r.maximum or '?'}"
            if r.model_ranges:
                bounds = "; ".join(f"{m}: {a}..{b}" for m, (a,b) in r.model_ranges.items())
            fields = [str(r.number), f"{r.name}: {r.meaning}", r.conversion, "yes" if r.signed else "no", r.unit or "context / raw", "context" if r.conversion == "reading" else str(r.precision), f"{r.access} / {r.write_policy}", bounds, r.source, r.restrictions]
            lines.append("| " + " | ".join(f.replace("|", "/").replace("\n", " ") for f in fields) + " |")
        lines += ["", f"### {family} STATUS2", "", "| Code | Meaning |", "| --- | --- |"]
        lines += [f"| {n} | {label} |" for n,label in sorted(profile.statuses.items())]
        lines += [""]
    return "\n".join(lines)


if __name__ == "__main__":
    (ROOT / "Docs" / "REGISTER_TABLES.md").write_text(render(), encoding="utf-8")
